"""Notebook 02: linear light, demosaicing, white balance, colour, and tone.

This notebook narrates the Phase 3 ISP chain with the same shared measurement
that produces the G3 gate report. It is a teaching companion, not a gate
artifact: it uses `measure_g3(quick=True)` and a smaller Siemens star, writes no
report, and never overwrites the committed `results/reports/g3_isp.md`.

The physics in the figures:

* **Linear light.** DPC, BLC, LSC, AWB, demosaicing, the colour-correction
  matrix, denoise, and sharpen all work on values proportional to radiance.
  BLC subtracts the ADC pedestal and divides by the white span, so saturation
  maps to 1.0. Tone is the first non-linear step: it applies the exposure trim
  in linear light, the sRGB-to-Display-P3 matrix when requested, the display
  clamp, and the sRGB OETF.
* **CFA reconstruction.** A Bayer mosaic measures one colour per site.
  Bilinear interpolation averages same-colour neighbours independently and
  zippers along edges; Malvar-He-Cutler adds a gradient correction borrowed
  from the measured green plane. Both are compared with the full-resolution
  reference on a colour Siemens star.
* **White balance.** A neutral patch under tungsten does not produce equal
  camera channels. Gray-world equalises per-CFA channel means; the expected
  gains here come from the analytic spectral response to a perfect diffuser,
  not from the estimator under test.
* **Colour correction.** The camera filters are not identical to the CIE
  observer. A 3x3 matrix fitted on 24 ColorChecker patches maps camera RGB to
  linear sRGB; CIEDE2000 against the spectrally computed reference measures the
  residual. The shipped synthetic CFA uses conventional Bayer bands (blue
  ~448 nm, green ~542 nm, red ~610 nm); the in-sample CCM meets the ΔE2000
  gates at both illuminants, and the Luther-condition residual is reported as
  a positive design check.
* **Tone and trace.** The pre-tone linear trace stage plus the tone
  configuration must reproduce both the rendered display array and the
  unclipped `linear_rgb` buffer, including exposure compensation and Display
  P3 primaries.

The notebook executes in well under two minutes on a laptop and honours
`CAMSIM_FIG_DIR` only if a cell saves a figure; this notebook displays inline
and writes nothing. The committed `.py` source is the notebook; no `.ipynb` is
committed.
"""

# %% [markdown]
# # 02 - ISP colour fundamentals
#
# This notebook follows one image through the image-signal processor:
#
# `RAW -> DPC -> BLC -> LSC -> AWB -> demosaic -> CCM -> denoise -> sharpen -> tone -> output`
#
# We use the shared `measure_g3(quick=True)` measurement and a quick stage
# gallery. Quick mode is a smoke run, not the G3 gate evidence; the committed
# report is generated by the full `examples/02_isp_stage_gallery.py` run.

# %%
import os

os.environ.setdefault("MPLBACKEND", "Agg")

import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
from IPython import get_ipython

from camsim.characterization import build_gallery, measure_g3
from camsim.isp.colorspace import linear_srgb_to_p3
from camsim.isp.tone import linear_to_srgb, srgb_to_linear
from camsim.viz import (
    PALETTE,
    plot_demosaic_comparison,
    plot_pipeline_trace,
    plot_zoom_crops,
    set_style,
)

# When executed by Jupyter, switch to the inline backend so every figure is
# embedded in the notebook. Outside Jupyter the Agg backend stays active.
_ipython = get_ipython()
if _ipython is not None:
    _ipython.run_line_magic("matplotlib", "inline")

set_style()

payload = measure_g3(quick=True)
gallery = build_gallery(quick=True)
print(f"G3 quick status: {payload['status']} (quick mode is not gate evidence)")
print("Stage order: " + " -> ".join(gallery.stages))

# %% [markdown]
# ## 1. Linear light and the pipeline order
#
# The contact sheet below shows every executed stage. Three display rules make
# the panels comparable:
#
# * the `dpc` panel is in ADC code units (tens to thousands of DN), before the
#   black pedestal is removed, so it is normalised by its own maximum;
# * every stage from `blc` through the last pre-tone stage is linear light and
#   shares **one** display scale, so brightness and colour changes are real;
# * `tone` and `output` are already display encoded and are not encoded twice.
#
# Per-panel auto-normalisation would hide exactly the black-level and
# white-balance errors this gallery exists to reveal.

# %%
figure, _axes = plot_pipeline_trace(gallery.stages)
plt.show()

# %% [markdown]
# The zoom view cuts the same high-gradient region from every stage. Nearest
# neighbour keeps individual pixels visible, which is what makes demosaic
# zippers, colour fringes, and sharpening halos legible.

# %%
figure, _axes = plot_zoom_crops(gallery.stages)
plt.show()

# %% [markdown]
# ## 2. Demosaicing: bilinear versus Malvar-He-Cutler
#
# Each reconstruction is compared with the full-resolution RGB image that was
# mosaiced. The red channel carries a 36-spoke star, green an 18-spoke star,
# and blue concentric rings, so the three channels have independent edges and
# the comparison is not trivially exact. The error maps share one linear-light
# colour scale; the summary prints the same max and mean absolute error that
# the gate tests use.
#
# Bilinear is cheap and exact for smooth fields, but interpolates each channel
# independently, so an edge that falls on a red site but not a blue one
# produces a colour fringe. MHC adds a correction proportional to the measured
# green plane's second derivative, recovering detail at about twice the cost.

# %%
figure, _axes = plot_demosaic_comparison(
    gallery.star_reference,
    gallery.star_bilinear,
    gallery.star_mhc,
)
plt.show()

demosaic = payload["demosaic"]
print(f"bilinear max |error|: {demosaic['bilinear_max_abs']:.3e} (gate <= 1e-5)")
print(f"MHC max |error|:      {demosaic['mhc_max_abs']:.3e} (gate <= 1e-4)")

# %% [markdown]
# ## 3. White balance
#
# The scene is a 50 % neutral flat field under D65 and 3000 K. Gray-world
# equalises the per-CFA-channel means, and the gains are normalised so green is
# exactly one. The expected gains are computed **independently** from the
# sensor's spectral response to a perfect diffuser: the integral of the
# illuminant times QE, IR-cut, and CFA over photon energy. If the expectation
# came from the same gray-world statistic, the check would be tautological.
#
# Tungsten (3000 K) needs a blue gain near 3 and a red gain below 1; daylight
# needs only a modest blue lift. Both estimates agree within about one percent.

# %%
for name, label in (("D65", "D65"), ("3000K", "3000 K")):
    section = payload["awb"]["illuminants"][name]
    print(f"{label}:")
    for index, channel in enumerate(("R", "G", "B")):
        print(
            f"  {channel}: expected {section['expected_gains'][index]:.4f}, "
            f"measured {section['measured_gains'][index]:.4f}, "
            f"relative error {100.0 * section['relative_errors'][index]:.2f} %"
        )
    print(f"  method: {section['method']}, confidence {section['confidence']:.3f}")

figure, axes = plt.subplots(1, 2, figsize=(9.6, 4.0), sharey=True)
for axis, name, title in zip(axes, ("D65", "3000K"), ("D65", "3000 K"), strict=True):
    section = payload["awb"]["illuminants"][name]
    positions = np.arange(3)
    axis.bar(positions - 0.18, section["expected_gains"], 0.36, color=PALETTE[0], label="analytic")
    axis.bar(
        positions + 0.18, section["measured_gains"], 0.36, color=PALETTE[4], label="gray-world"
    )
    axis.set_xticks(positions)
    axis.set_xticklabels(("R", "G", "B"))
    axis.set_title(title)
    axis.set_ylim(bottom=0.0)
    axis.legend(loc="upper left", fontsize=8.0)
axes[0].set_ylabel("Gain (green = 1)")
figure.suptitle("White-balance gains: analytic expectation versus gray-world")
figure.tight_layout()
plt.show()

# %% [markdown]
# The injected-cast check makes the same point without relying on the
# illuminant spectrum: multiply the red CFA sites by 1.6 and the blue sites by
# 0.7, then require the estimator to invert that scaling on top of the
# illuminant cast.

# %%
injected = payload["awb"]["injected_scaling"]
print(f"injection (R, G, B): {injected['injection']}")
for name in ("D65", "3000K"):
    section = injected["illuminants"][name]
    print(
        f"  {name}: expected {np.round(section['expected_gains'], 4)}, "
        f"measured {np.round(section['measured_gains'], 4)}, "
        f"max error {100.0 * injected['max_relative_error']:.2f} %"
    )

# %% [markdown]
# ## 4. Colour correction and ΔE2000
#
# The reference Lab is computed spectrally from the ColorChecker reflectance,
# the scene illuminant, and the CIE 1931 observer. To fit a camera-to-sRGB
# matrix we convert it back to XYZ with the scene white point, adapt to D65
# with the Bradford transform, and convert to **linear** sRGB (no OETF). The
# camera RGB is white-balanced to a perfect diffuser and divided by its
# perfect-diffuser level, so a row-sum matrix preserves the neutral axis.
#
# One ridge-regularised 3x3 matrix per illuminant is fitted on the same 24
# patches used for evaluation. The per-patch ΔE2000 below is therefore
# **in-sample**: it measures whether the ISP can represent the calibration
# scene, not whether it generalises to a held-out chart.
#
# The shipped synthetic CFA uses conventional Bayer bands (blue ~448 nm,
# green ~542 nm, red ~610 nm) with moderate out-of-band leakage. The in-sample
# 3x3 CCM meets the ΔE2000 gates at both illuminants; the Luther diagnostic
# below is a positive check that the CFA spans the CIE observer.

# %%
d65 = payload["colorchecker"]["illuminants"]["D65"]
warm = payload["colorchecker"]["illuminants"]["3000K"]
print("Fitted CCM rows (row sums are one):")
for name, section in (("D65", d65), ("3000K", warm)):
    print(f"  {name}:")
    for row in section["ccm"]:
        print("    " + "  ".join(f"{value:+.4f}" for value in row))

positions = np.arange(len(d65["patch_names"]))
figure, axis = plt.subplots(figsize=(12.0, 4.7))
axis.bar(
    positions - 0.2,
    d65["delta_e2000"],
    0.4,
    color=PALETTE[0],
    label=f"D65 mean {d65['delta_e2000_mean']:.2f}",
)
axis.bar(
    positions + 0.2,
    warm["delta_e2000"],
    0.4,
    color=PALETTE[4],
    label=f"3000 K mean {warm['delta_e2000_mean']:.2f}",
)
axis.axhline(2.0, color=PALETTE[0], linestyle="--", linewidth=1.0, label="D65 gate 2.0")
axis.axhline(4.0, color=PALETTE[4], linestyle=":", linewidth=1.0, label="3000 K gate 4.0")
axis.set_xticks(positions)
axis.set_xticklabels(d65["patch_names"], rotation=55, ha="right", fontsize=7.5)
axis.set_ylabel("CIEDE2000")
axis.set_title("ColorChecker ΔE2000 per patch (in-sample 3x3 CCM)")
axis.legend(loc="upper right", fontsize=8.0)
axis.set_ylim(bottom=0.0)
figure.tight_layout()
plt.show()

print(f"D65 mean: {d65['delta_e2000_mean']:.3f}, max {d65['delta_e2000_max']:.3f}")
print(f"3000 K mean: {warm['delta_e2000_mean']:.3f}, max {warm['delta_e2000_max']:.3f}")
margin = (4.0 - warm["delta_e2000_mean"]) / 4.0 * 100.0
order = sorted(
    range(len(warm["delta_e2000"])),
    key=lambda index: warm["delta_e2000"][index],
    reverse=True,
)
print(
    f"3000 K margin: {margin:.2f}% below the 4.0 mean limit; per-patch maxima: "
    f"{warm['delta_e2000'][order[0]]:.3f} ({warm['patch_names'][order[0]]}), "
    f"{warm['delta_e2000'][order[1]]:.3f} ({warm['patch_names'][order[1]]})"
)

# %% [markdown]
# The Luther-condition diagnostic is a design check on the CFA. It asks
# whether the sensor's spectral sensitivities are a linear combination of the
# CIE colour matching functions. With the conventional bands the relative
# residual is small; a large residual would mean a 3x3 matrix cannot be exact,
# no matter how it is fitted.

# %%
luther = payload["sensor_colorimetry"]
print(f"Luther-condition relative residual: {luther['luther_relative_residual']:.3f}")
print(f"CFA projection condition number:   {luther['condition_number']:.1f}")
print(f"R/G channel correlation:           {luther['channel_correlation'][0][1]:.3f}")

# %% [markdown]
# ## 5. Tone curve and Display P3
#
# The tone stage applies the exposure trim and the sRGB-to-P3 matrix in linear
# light, clamps to the display range, and then applies the sRGB OETF. The OETF
# has a linear toe near black so the curve is invertible and does not amplify
# shadow noise; the power segment approximates the eye's response over most of
# the range. Display P3 uses the same transfer curve and different primaries.
#
# The plot below compares the camsim OETF with the linear identity, and the
# code shows that encoding for P3 then decoding gives a different RGB triple
# because the primaries differ, while the underlying linear light is unchanged.

# %%
samples = np.linspace(0.0, 1.0, 1001)
figure, axis = plt.subplots(figsize=(7.6, 4.0))
axis.plot(samples, linear_to_srgb(samples), color=PALETTE[0], label="sRGB OETF")
axis.plot(
    samples, samples, color=PALETTE[7], linestyle="--", linewidth=1.0, label="linear identity"
)
axis.set_xlabel("Linear light")
axis.set_ylabel("Display code value")
axis.set_title("The sRGB OETF is the only non-linear step")
axis.legend(loc="best")
figure.tight_layout()
plt.show()

linear_colour = np.array([[0.2, 0.4, 0.1]], dtype=np.float64)
p3_display = linear_srgb_to_p3(linear_colour)
p3_linear = srgb_to_linear(p3_display)
print(f"linear sRGB      : {np.round(linear_colour[0], 4)}")
print(f"encoded P3       : {np.round(p3_display[0], 4)}")
print(f"decoded P3 linear: {np.round(p3_linear[0], 4)} (same tristimulus, different primaries)")

# %% [markdown]
# ## 6. Stage-trace consistency
#
# A trace is only useful if it reproduces the processing that produced the
# final image. The check applies the tone configuration to the last linear
# trace stage and requires it to match both the rendered display array and the
# unclipped `linear_rgb` buffer at +0.5 EV in Display P3. The display and linear
# errors below are at float32 round-off.

# %%
trace = payload["trace"]
print("Trace stages: " + " -> ".join(trace["stage_names"]))
print(f"Color space: {trace['color_space']}, exposure: {trace['exposure_ev']:+.1f} EV")
print(f"Display reproduction max |error|:    {trace['tone_max_abs']:.3e}")
print(f"linear_rgb reproduction max |error|: {trace['linear_rgb_max_abs']:.3e}")
print(f"Pre-tone linearity max relative error: {payload['linearity']['max_relative_error']:.3e}")

