def test_g3_report_tables_match_results_json() -> None:
    """Every committed report table cell must match the committed JSON.

    The report is generated by the full example run, not hand-edited. Parsing
    it back and comparing names, measured values, tolerances, and verdicts
    turns a stale report into a test failure instead of a plausible-looking
    but outdated gate artifact.
    """
    assert G3_JSON_PATH.exists(), f"missing gate JSON: {G3_JSON_PATH}"
    assert G3_REPORT_PATH.exists(), f"missing gate report: {G3_REPORT_PATH}"
    payload = json.loads(G3_JSON_PATH.read_text(encoding="utf-8"))
    text = G3_REPORT_PATH.read_text(encoding="utf-8")

    assert payload["kind"] == "camsim G3 ISP validation"
    assert payload["gate_evidence"] is True
    assert payload["quick"] is False
    assert f"**Status: {payload['status']}**" in text

    tables = _parse_markdown_tables(text)

    # Verdict summary: every check, in order, with its exact display strings.
    rows = _table_with_header(tables, ["Check", "Measured", "Tolerance", "Result"])
    checks = payload["checks"]
    assert len(rows) == len(checks)
    for row, check in zip(rows, checks, strict=True):
        assert row[0] == check["name"]
        assert row[1] == check["measured_text"]
        assert row[2] == check["tolerance_text"]
        assert row[3] == ("PASS" if check["pass"] else "FAIL")
        parsed = _numbers(row[1])
        assert parsed and math.isclose(parsed[0], check["measured"], rel_tol=1e-3, abs_tol=1e-12)
        tolerance_numbers = _numbers(row[2])
        assert tolerance_numbers
        # A target + absolute tolerance prints both numbers; a maximum or
        # minimum prints one. Every parsed number must match one of the JSON
        # tolerance values, independent of JSON key ordering.
        expected_tolerance = [float(value) for value in check["tolerance"].values()]
        assert all(
            any(
                math.isclose(parsed, expected, rel_tol=1e-6, abs_tol=1e-12)
                for expected in expected_tolerance
            )
            for parsed in tolerance_numbers
        )

    # White-balance table: expected, measured, and relative error per channel.
    rows = _table_with_header(
        tables,
        ["Illuminant", "Channel", "Expected gain", "Measured gain", "Relative error", "Result"],
    )
    awb = payload["awb"]["illuminants"]
    assert len(rows) == 3 * len(awb)
    for row in rows:
        section = awb[row[0]]
        channel = ("R", "G", "B").index(row[1])
        assert math.isclose(
            _numbers(row[2])[0], section["expected_gains"][channel], rel_tol=1e-4, abs_tol=0.0
        )
        assert math.isclose(
            _numbers(row[3])[0], section["measured_gains"][channel], rel_tol=1e-4, abs_tol=0.0
        )
        assert math.isclose(
            _numbers(row[4])[0], section["relative_errors"][channel], rel_tol=1e-3, abs_tol=1e-6
        )

    # Per-patch ColorChecker ΔE for both illuminants.
    rows = _table_with_header(tables, ["Patch", "D65 deltaE2000", "3000 K deltaE2000"])
    d65 = payload["colorchecker"]["illuminants"]["D65"]
    warm = payload["colorchecker"]["illuminants"]["3000K"]
    assert len(rows) == 24
    for index, row in enumerate(rows):
        assert row[0] == d65["patch_names"][index] == warm["patch_names"][index]
        # The report prints ΔE to three decimals; the absolute allowance
        # matches that display precision without weakening the gate.
        assert math.isclose(
            _numbers(row[1])[0], d65["delta_e2000"][index], rel_tol=1e-3, abs_tol=1e-3
        )
        assert math.isclose(
            _numbers(row[2])[0], warm["delta_e2000"][index], rel_tol=1e-3, abs_tol=1e-3
        )

    # Colour-correction matrices, one row per illuminant.
    rows = _table_with_header(tables, ["Illuminant", "Row 1", "Row 2", "Row 3"])
    assert len(rows) == 2
    for row in rows:
        matrix = payload["colorchecker"]["illuminants"][row[0]]["ccm"]
        for matrix_row, cell in zip(matrix, row[1:], strict=True):
            values = _numbers(cell)
            assert len(values) == 3
            assert all(
                math.isclose(value, expected, rel_tol=1e-4, abs_tol=1e-6)
                for value, expected in zip(values, matrix_row, strict=True)
            )


