"""G3 gate tests: the ISP stage gallery, notebook evidence, and report.

The G3 gate closes Phase 3 by checking the image-signal processor end to end:
the enforced stage order and trace, colour correction against the spectrally
computed ColorChecker reference, white-balance recovery, reference-library
agreement for bilinear and Malvar-He-Cutler demosaicing, the standard sRGB
OETF, linear-space invariance, lens-shading correction, denoise signal-to-noise
gain with edge preservation, sharpening overshoot, and the RCCC baseline.

Two evidence levels are distinguished. ``measure_g3(quick=True)`` is the fast
executable form used by these tests: it exercises every measurement on a
smaller chart and is **not** gate evidence. The committed
``results/reports/g3_isp_results.json`` and ``results/reports/g3_isp.md`` are
generated by the full run of ``examples/02_isp_stage_gallery.py`` and are the
gate artifacts. ``test_g3_report_tables_match_results_json`` parses the
committed Markdown tables and compares every cell with the JSON, so a stale
report fails instead of being accepted as evidence.

The ColorChecker criterion is measured honestly. The design gate is mean
ΔE2000 < 2.0 under D65 and < 4.0 under 3000 K after an in-sample 3x3 CCM.
The shipped flagship preset now uses synthetic **conventional Bayer bands**
(blue ~448 nm, green ~542 nm, red ~610 nm) with moderate out-of-band leakage;
the original broad, nearly collinear CFA curves were replaced after the G3
gate showed that no 3x3 matrix could colour-correct them. The new curves leave
a much smaller Luther-condition residual, and the in-sample CCM now meets both
thresholds. ``test_g3_colorchecker_delta_e_threshold`` asserts the physical
gate; ``test_g3_colorchecker_delta_e_verdict_is_honest`` separately asserts
that the recorded thresholds are still exactly 2.0 / 4.0 and that the verdict
is the strict comparison of the measured value against them.
"""

from __future__ import annotations

import json
import math
import os
import subprocess
import sys
from pathlib import Path
from typing import Any

import pytest

from camsim.characterization import measure_g3

REPO_ROOT = Path(__file__).resolve().parents[1]
EXAMPLE_PATH = REPO_ROOT / "examples" / "02_isp_stage_gallery.py"
G3_REPORT_PATH = REPO_ROOT / "results" / "reports" / "g3_isp.md"
G3_JSON_PATH = REPO_ROOT / "results" / "reports" / "g3_isp_results.json"
QUICK_REPORT_NAME = "g3_isp_results_quick.json"


@pytest.fixture(scope="module")
def g3() -> dict[str, Any]:
    """Run the quick G3 measurement once for every test in this module."""
    return measure_g3(quick=True)


def _check(g3: dict[str, Any], name: str) -> dict[str, Any]:
    """Return one named check, failing clearly when it is absent."""
    for check in g3["checks"]:
        if check["name"] == name:
            return check
    raise AssertionError(f"missing G3 check {name!r}; got {[c['name'] for c in g3['checks']]}")


def _parse_markdown_tables(text: str) -> list[tuple[list[str], list[list[str]]]]:
    """Parse every GitHub-style table into a header and data rows.

    A table starts with a pipe-delimited header followed by a separator row of
    dashes and optional colons. Blank lines end a table. Cells are stripped of
    surrounding whitespace so the comparison does not depend on source
    indentation.
    """
    lines = text.splitlines()
    tables: list[tuple[list[str], list[list[str]]]] = []
    index = 0
    while index < len(lines) - 1:
        header_line = lines[index].strip()
        separator = lines[index + 1].strip()
        if not (header_line.startswith("|") and separator.startswith("|")):
            index += 1
            continue
        separators = [cell.strip() for cell in separator.strip("|").split("|")]
        if not all(set(cell) <= {"-", ":"} and cell for cell in separators):
            index += 1
            continue
        header = [cell.strip() for cell in header_line.strip("|").split("|")]
        rows: list[list[str]] = []
        index += 2
        while index < len(lines) and lines[index].strip().startswith("|"):
            rows.append([cell.strip() for cell in lines[index].strip().strip("|").split("|")])
            index += 1
        tables.append((header, rows))
    return tables


def _table_with_header(
    tables: list[tuple[list[str], list[list[str]]]], header: list[str]
) -> list[list[str]]:
    """Return the rows of the table whose header matches exactly."""
    for candidate, rows in tables:
        if candidate == header:
            return rows
    raise AssertionError(f"missing table with header {header!r}")


def _numbers(cell: str) -> list[float]:
    """Parse every float in a cell, allowing prose and unit labels."""
    values: list[float] = []
    for token in cell.replace(",", " ").split():
        try:
            values.append(float(token))
        except ValueError:
            continue
    return values


def test_example_02_runs(tmp_path: Path) -> None:
    """Run example 02 in quick mode with temporary artifact directories."""
    figures = tmp_path / "figures"
    reports = tmp_path / "reports"
    env = {
        **os.environ,
        "CAMSIM_FIG_DIR": str(figures),
        "MPLBACKEND": "Agg",
    }
    result = subprocess.run(
        [
            sys.executable,
            str(EXAMPLE_PATH),
            "--quick",
            "--report-dir",
            str(reports),
        ],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        env=env,
        timeout=180,
        check=False,
    )

    assert result.returncode == 0, result.stderr
    quick_path = reports / QUICK_REPORT_NAME
    assert quick_path.exists(), f"missing quick report: {quick_path}"
    payload = json.loads(quick_path.read_text(encoding="utf-8"))
    assert payload["kind"] == "camsim G3 ISP validation"
    assert payload["gate_evidence"] is False
    assert payload["quick"] is True
    assert payload["checks"]
    for check in payload["checks"]:
        assert {"name", "measured", "tolerance", "pass", "notes"} <= set(check)
        assert check["tolerance"]
    assert payload["status"] in {"PASS", "FAIL"}

    # The gallery must contain real figures, not an empty directory.
    gallery = sorted(figures.glob("02_*.png"))
    assert len(gallery) >= 3, [path.name for path in gallery]
    for path in gallery:
        assert path.stat().st_size > 0

    # Quick mode must never write or overwrite the committed gate artifacts.
    assert not (reports / "g3_isp_results.json").exists()
    assert not (reports / "g3_isp.md").exists()


def test_g3_colorchecker_delta_e_threshold(g3: dict[str, Any]) -> None:
    """Mean ColorChecker ΔE2000 must be below 2.0 (D65) and 4.0 (3000 K)."""
    d65 = _check(g3, "ColorChecker mean deltaE2000 (D65)")
    warm = _check(g3, "ColorChecker mean deltaE2000 (3000 K)")
    assert d65["measured"] < 2.0
    assert warm["measured"] < 4.0


def test_g3_colorchecker_delta_e_verdict_is_honest(g3: dict[str, Any]) -> None:
    """The gate thresholds stay at 2.0/4.0 and the verdict is the strict comparison."""
    d65 = _check(g3, "ColorChecker mean deltaE2000 (D65)")
    warm = _check(g3, "ColorChecker mean deltaE2000 (3000 K)")
    assert d65["tolerance"] == {"maximum": 2.0}
    assert warm["tolerance"] == {"maximum": 4.0}

    sections = g3["colorchecker"]["illuminants"]
    for check, name in ((d65, "D65"), (warm, "3000K")):
        section = sections[name]
        assert check["measured"] == pytest.approx(section["delta_e2000_mean"])
        assert check["pass"] is (section["delta_e2000_mean"] < check["tolerance"]["maximum"])
        per_patch = section["delta_e2000"]
        assert len(per_patch) == 24
        assert section["delta_e2000_mean"] == pytest.approx(sum(per_patch) / len(per_patch))
        assert section["delta_e2000_max"] == pytest.approx(max(per_patch))

    # The re-authored conventional Bayer CFA resolves the former colour
    # defect: both illuminants now pass, and the spectral diagnostic reflects
    # a well-conditioned, non-collinear set of sensitivities.
    assert d65["pass"], d65
    assert warm["pass"], warm
    assert d65["measured"] < 2.0
    assert warm["measured"] < 4.0
    diagnostic = g3["sensor_colorimetry"]
    assert diagnostic["luther_relative_residual"] < 0.2
    assert abs(diagnostic["channel_correlation"][0][1]) < 0.5


def test_g3_awb_recovers_gains(g3: dict[str, Any]) -> None:
    """Analytic white gains and an injected cast are recovered within 5 %."""
    for name in ("D65", "3000K"):
        section = g3["awb"]["illuminants"][name]
        expected = section["expected_gains"]
        measured = section["measured_gains"]
        errors = section["relative_errors"]
        assert measured[1] == pytest.approx(1.0)
        assert expected[1] == pytest.approx(1.0)
        for index in (0, 2):
            assert errors[index] <= 0.05, (name, index, errors)
            assert math.isclose(measured[index], expected[index], rel_tol=0.05)
        assert section["method"] == "gray_world"

    injected = g3["awb"]["injected_scaling"]
    assert injected["injection"] == [1.6, 1.0, 0.7]
    assert injected["max_relative_error"] <= 0.05
    for check in g3["checks"]:
        if check["name"].startswith("AWB"):
            assert check["pass"], check


