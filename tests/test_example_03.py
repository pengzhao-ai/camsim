def test_g4_report_tables_match_results_json() -> None:
    """Every committed report table cell must match the committed JSON."""
    assert G4_JSON_PATH.exists(), f"missing gate JSON: {G4_JSON_PATH}"
    assert G4_REPORT_PATH.exists(), f"missing gate report: {G4_REPORT_PATH}"
    payload = json.loads(G4_JSON_PATH.read_text(encoding="utf-8"))
    text = G4_REPORT_PATH.read_text(encoding="utf-8")
    # The committed report must be byte-identical to a fresh render of the
    # committed JSON. The table checks below localize a failure; this guard
    # makes the completeness claim exact.
    assert text == render_g4_report(payload)
    tables = _parse_markdown_tables(text)

    # Verdict summary: every check, in order, with its exact display strings.
    rows = _table_with_header(tables, ["Check", "Measured", "Tolerance", "Result"])
    checks = payload["checks"]
    assert len(rows) == len(checks)
    for row, check in zip(rows, checks, strict=True):
        assert row[0] == check["name"]
        assert row[1] == check["measured_text"]
        assert row[2] == check["tolerance_text"]
        assert row[3] == ("PASS" if check["pass"] else "FAIL")
        parsed = _numbers(row[1])
        assert parsed and math.isclose(parsed[0], check["measured"], rel_tol=1e-3, abs_tol=1e-12)
        expected_tolerance = [float(value) for value in check["tolerance"].values()]
        tolerance_numbers = _numbers(row[2])
        assert tolerance_numbers
        assert all(
            any(
                # Tolerance display is six significant digits, so allow one
                # part in 1e5 rather than the exact float round-trip.
                math.isclose(parsed_value, expected, rel_tol=1e-5, abs_tol=1e-12)
                for expected in expected_tolerance
            )
            for parsed_value in tolerance_numbers
        )

    # Analytic MTF table: measured, reference, and relative error per case.
    header = [
        "Case",
        "MTF50 measured",
        "MTF50 analytic",
        "MTF50 rel. error",
        "MTF20 measured",
        "MTF20 analytic",
        "MTF20 rel. error",
    ]
    rows = _table_with_header(tables, header)
    cases = payload["mtf"]["cases"]
    assert len(rows) == len(cases)
    for row, case in zip(rows, cases, strict=True):
        assert row[0] == case["name"]
        for column, field in ((1, "measured_mtf50_cp"), (2, "reference_mtf50_cp")):
            value = case[field]
            assert math.isclose(_numbers(row[column])[0], value, rel_tol=1e-3, abs_tol=1e-9)
        assert math.isclose(
            _numbers(row[3])[0], case["relative_error_mtf50"], rel_tol=1e-3, abs_tol=1e-12
        )
        for column, field in ((4, "measured_mtf20_cp"), (5, "reference_mtf20_cp")):
            value = case[field]
            if value is None:
                assert "not reached" in row[column]
            else:
                assert math.isclose(_numbers(row[column])[0], value, rel_tol=1e-3, abs_tol=1e-9)
        assert math.isclose(
            _numbers(row[6])[0], case["relative_error_mtf20"], rel_tol=1e-3, abs_tol=1e-12
        )

    # Angle-robustness table.
    rows = _table_with_header(tables, ["Case", "5 deg", "10 deg", "15 deg", "20 deg", "Spread %"])
    angle_rows = payload["mtf"]["angle_robustness"]
    assert len(rows) == len(angle_rows)
    for row, section in zip(rows, angle_rows, strict=True):
        assert row[0] == section["case"]
        for column, value in enumerate(section["mtf50_cp"], start=1):
            assert math.isclose(_numbers(row[column])[0], value, rel_tol=1e-3, abs_tol=1e-9)
        assert math.isclose(
            _numbers(row[5])[0], 100.0 * section["spread_fraction"], rel_tol=1e-3, abs_tol=1e-9
        )

    # SNR table: every spatial channel, the temporal estimate, and mono.
    rows = _table_with_header(
        tables, ["Measurement", "Mean", "Std", "SNR (dB)", "Expected (dB)", "Error (dB)"]
    )
    sections = [*payload["snr"]["spatial"]["measurements"], payload["snr"]["temporal"]]
    sections.append(payload["snr"]["mono"])
    assert len(rows) == len(sections)
    for row, section in zip(rows, sections, strict=True):
        columns = (
            (1, "mean"),
            (2, "std"),
            (3, "snr_db"),
            (4, "expected_snr_db"),
            (5, "error_db"),
        )
        for column, field in columns:
            assert math.isclose(
                _numbers(row[column])[0], section[field], rel_tol=1e-3, abs_tol=1e-9
            )

    # Delta-E table: every pair against colour-science.
    rows = _table_with_header(
        tables,
        [
            "Pair",
            "Source",
            "Our deltaE76",
            "Reference deltaE76",
            "Our deltaE2000",
            "Reference deltaE2000",
        ],
    )
    pairs = payload["color"]["pairs"]
    assert len(rows) == len(pairs)
    for row, pair in zip(rows, pairs, strict=True):
        assert row[0] == pair["name"]
        assert row[1] == pair["source"]
        for column, field in (
            (2, "delta_e76"),
            (3, "reference_delta_e76"),
            (4, "delta_e2000"),
            (5, "reference_delta_e2000"),
        ):
            assert math.isclose(_numbers(row[column])[0], pair[field], rel_tol=1e-3, abs_tol=1e-9)

    # Per-patch synthetic-chart delta-E table.
    rows = _table_with_header(tables, ["Patch", "deltaE76", "deltaE2000"])
    chart = payload["measure_all"]["chart"]
    assert len(rows) == len(chart["patch_names"])
    for index, row in enumerate(rows):
        assert row[0] == chart["patch_names"][index]
        assert math.isclose(
            _numbers(row[1])[0],
            chart["per_patch_delta_e76"][index],
            rel_tol=1e-3,
            abs_tol=1e-9,
        )
        assert math.isclose(
            _numbers(row[2])[0],
            chart["per_patch_delta_e2000"][index],
            rel_tol=1e-3,
            abs_tol=1e-9,
        )

    # Per-patch synthetic-chart SNR table.
    rows = _table_with_header(tables, ["Patch", "R", "G", "B", "Luma"])
    assert len(rows) == len(chart["per_patch_snr_db"])
    for row, section in zip(rows, chart["per_patch_snr_db"], strict=True):
        assert row[0] == section["patch"]
        for column, channel in enumerate(("R", "G", "B", "luma"), start=1):
            assert math.isclose(
                _numbers(row[column])[0], section[channel], rel_tol=1e-3, abs_tol=1e-9
            )

    # Acutance-versus-blur table.
    rows = _table_with_header(tables, ["Gaussian blur sigma (px)", "Acutance"])
    sweep = payload["acutance_sweep"]
    assert len(rows) == len(sweep["sigma_px"])
    for row, sigma, acutance in zip(rows, sweep["sigma_px"], sweep["acutance"], strict=True):
        assert math.isclose(_numbers(row[0])[0], sigma, rel_tol=1e-6, abs_tol=1e-12)
        assert math.isclose(_numbers(row[1])[0], acutance, rel_tol=1e-3, abs_tol=1e-9)

    # Illustrative lux sweep, serialized in the committed payload as
    # non-gate evidence.
    lux_sweep = payload["lux_sweep"]
