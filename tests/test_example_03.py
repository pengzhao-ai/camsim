def _check(g4: dict[str, Any], name: str) -> dict[str, Any]:
    """Return one named check, failing clearly when it is absent."""
    for check in g4["checks"]:
        if check["name"] == name:
            return check
    raise AssertionError(f"missing G4 check {name!r}; got {[c['name'] for c in g4['checks']]}")


def _case(g4: dict[str, Any], key: str) -> dict[str, Any]:
    """Return one MTF case by its stable key."""
    for case in g4["mtf"]["cases"]:
        if case["key"] == key:
            return case
    raise AssertionError(f"missing MTF case {key!r}")


def _parse_markdown_tables(text: str) -> list[tuple[list[str], list[list[str]]]]:
    """Parse every GitHub-style table into a header and data rows."""
    lines = text.splitlines()
    tables: list[tuple[list[str], list[list[str]]]] = []
    index = 0
    while index < len(lines) - 1:
        header_line = lines[index].strip()
        separator = lines[index + 1].strip()
        if not (header_line.startswith("|") and separator.startswith("|")):
            index += 1
            continue
        separators = [cell.strip() for cell in separator.strip("|").split("|")]
        if not all(set(cell) <= {"-", ":"} and cell for cell in separators):
            index += 1
            continue
        header = [cell.strip() for cell in header_line.strip("|").split("|")]
        rows: list[list[str]] = []
        index += 2
        while index < len(lines) and lines[index].strip().startswith("|"):
            rows.append([cell.strip() for cell in lines[index].strip().strip("|").split("|")])
            index += 1
        tables.append((header, rows))
    return tables


def _table_with_header(
    tables: list[tuple[list[str], list[list[str]]]], header: list[str]
) -> list[list[str]]:
    """Return the rows of the table whose header matches exactly."""
    for candidate, rows in tables:
        if candidate == header:
            return rows
    raise AssertionError(f"missing table with header {header!r}")


def _numbers(cell: str) -> list[float]:
    """Parse every float in a cell, allowing prose and unit labels."""
    values: list[float] = []
    for token in cell.replace(",", " ").split():
        try:
            values.append(float(token))
        except ValueError:
            continue
    return values


