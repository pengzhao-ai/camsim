"""G4 gate tests: analytic MTF/SNR/colour validation and the metrics gallery.

The G4 gate closes Phase 4 by checking the independent image-quality harness
against analytic references that share no code with it:

* **MTF.** A slanted edge blurred by a known Gaussian, box, or Airy PSF is
  measured with :func:`camsim.metrics.slanted_edge_mtf`; the MTF50 and MTF20
  crossings are compared with the exact discrete transfer function
  :func:`camsim.optics.psf.psf_mtf` of the same kernel. Every gate case uses
  8x analysis oversampling, because 4x carries about a 2 % bias for
  near-diffraction-limited systems.
* **SNR.** A synthetic flat patch with known Gaussian noise must recover
  ``20 log10(mean / std)`` per channel and in luma. A temporal stack with a
  static fixed pattern plus temporal noise must recover the temporal-noise
  SNR, while the single-frame spatial SNR must be materially lower because it
  counts the fixed pattern as noise.
* **Colour.** :func:`camsim.metrics.color._delta_e76` and
  :func:`camsim.metrics.color._delta_e2000` are compared with
  ``colour.delta_E`` on neutral, lightness, hue-rotation, and the published
  Sharma CIEDE2000 pairs.
* **Harness.** A synthetic ColorChecker-like chart built from the spectrally
  computed reference is measured with :func:`camsim.metrics.measure_all`; the
  report must be complete, strictly JSON-serializable with NaN crossings as
  ``null``, and the metrics layer must stay import-independent of the
  simulator.

Two evidence levels are distinguished. ``measure_g4(quick=True)`` is the fast
executable form used by these tests and is **not** gate evidence. The committed
``results/reports/g4_metrics_results.json`` and ``results/reports/g4_metrics.md``
are generated by the full run of ``examples/03_measure_iq.py`` and are the gate
artifacts. ``test_g4_report_tables_match_results_json`` parses the committed
Markdown tables and compares every numeric cell with the JSON, so a stale
report fails instead of being accepted.
"""

