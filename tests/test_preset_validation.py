"""G2 preset gate: the shipped flagship sensor recovers its datasheet-style values.

The G2 gate closes Phase 2 by proving that a sensor configured with known
parameters can be measured back through the EMVA 1288-style characterization.
This module is the executable form of that gate for the shipped preset: it
loads the preset through the production loader, characterizes the low
conversion-gain mode with 32 frames per level, and checks the measured read
noise, DSNU, PRNU, saturation capacity, linearity, and dynamic range against the
design tolerances.

Thirty-two frames per level is deliberate. The LCG dark offset is only about
0.06 DN, so an eight-frame dark average leaves a seed-dependent DSNU spread
that can exceed the 10 % gate; 32 frames average the residual row-noise and
quantization coupling enough for a stable measurement. The separate eight-frame
robustness sweep in ``tests/test_characterization.py`` carries a documented
20 % DSNU waiver and is not the G2 evidence.

The measured values belong to the preset in this checkout. A change to the ADC,
full well, conversion gain, DSNU, PRNU, or spectral curves invalidates them and
requires re-running the characterization and the G2 report.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

import camsim
from camsim.characterization import characterize_sensor
from camsim.config.io import load_sensor

REPO_ROOT = Path(__file__).resolve().parents[1]
SENSOR_PRESET = (
    REPO_ROOT / "src" / "camsim" / "config" / "presets" / "sensors" / "flagship_phone_50mp.json"
)
G2_REPORT_PATH = REPO_ROOT / "results" / "reports" / "g2_sensor.md"
G2_RESULTS_PATH = REPO_ROOT / "results" / "reports" / "g2_sensor_results.json"
G2_FIGURE_NAMES = (
    "g2_qe_cfa_ir_cut.png",
    "g2_ptc.png",
    "g2_snr_vs_irradiance.png",
    "g2_dark_current_vs_temperature.png",
    "g2_lcg_hcg_comparison.png",
    "g2_dsnu_prnu_histograms.png",
)
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"


def test_preset_g2_recovery() -> None:
    """The flagship LCG mode recovers every G2 quantity within tolerance."""
    cfg = load_sensor(SENSOR_PRESET)
    sensor = camsim.Sensor(cfg, seed=5)
    report = characterize_sensor(
        sensor,
        irradiance_levels=[2e-4, 5e-4, 1e-3, 2e-3, 5e-3, 1e-2, 2e-2, 4e-2, 8e-2],
        frames_per_level=32,
        mode="LCG",
        exposure_s=0.01,
        base_seed=9,
    )
    assert report.linearity_residual < 0.05
    assert 30.0 < report.dynamic_range_db < 90.0
    assert report.read_noise_e == pytest.approx(2.0, rel=0.05)
    assert report.dsnu_e == pytest.approx(0.5, rel=0.10)
    assert report.prnu_percent == pytest.approx(0.5, rel=0.10)
    assert report.saturation_capacity_e == pytest.approx(6000.0, rel=0.10)


def test_g2_report_and_figures_are_present() -> None:
    """The committed G2 report and its six figures are gate evidence, not stubs."""
    text = G2_REPORT_PATH.read_text(encoding="utf-8")
    assert "**Status: PASS**" in text
    assert "Assumptions and limitations" in text
    for name in G2_FIGURE_NAMES:
        path = REPO_ROOT / "results" / "figures" / name
        assert path.stat().st_size > 0, f"missing G2 figure: {name}"
        assert path.read_bytes()[:8] == PNG_MAGIC


def _markdown_tables(text: str) -> list[dict[str, list[str] | list[list[str]]]]:
    """Parse the report's pipe tables into header and rows."""
    tables: list[dict[str, list[str] | list[list[str]]]] = []
    current: dict[str, list[str] | list[list[str]]] | None = None
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("|") and stripped.endswith("|"):
            cells = [cell.strip() for cell in stripped.strip("|").split("|")]
            if current is None:
                current = {"header": cells, "rows": []}
                continue
            if all(set(cell) <= set("-: ") for cell in cells):
                continue
            rows = current["rows"]
            assert isinstance(rows, list)
            rows.append(cells)
        elif current is not None:
            tables.append(current)
            current = None
    if current is not None:
        tables.append(current)
    return tables


def _first_number(cell: str) -> float:
    """Return the first signed decimal/scientific number in a table cell."""
    match = re.search(r"[-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?", cell)
    assert match is not None, f"no number in {cell!r}"
    return float(match.group(0))


def test_g2_report_tables_match_results_json() -> None:
    """Every headline and dark-current number in the report matches the JSON.

    The Markdown report and the machine-readable results are generated by the
    same run but stored separately. This test parses the numeric cells and
    compares them with the JSON, so a preset or model change that regenerates
    one artifact without the other fails the gate instead of leaving stale
    prose behind.
    """
    payload = json.loads(G2_RESULTS_PATH.read_text(encoding="utf-8"))
    tables = _markdown_tables(G2_REPORT_PATH.read_text(encoding="utf-8"))
    summary = next(table for table in tables if str(table["header"][0]) == "Check")
    summary_rows = {
        str(row[0]): row for row in summary["rows"] if isinstance(row, list) and len(row) == 4
    }

    lcg = payload["LCG"]
    hcg = payload["HCG"]
    expected = {
        "LCG read noise": lcg["read_noise_e"],
        "LCG DSNU": lcg["dsnu_e"],
        "LCG PRNU": lcg["prnu_percent"],
        "LCG saturation capacity": lcg["saturation_capacity_e"],
        "LCG linearity residual": lcg["linearity_residual"],
        "LCG dynamic range": lcg["dynamic_range_db"],
        "LCG system gain relative error": abs(lcg["provenance"]["system_gain_relative_error"])
        * 100.0,
        "HCG read noise": hcg["read_noise_e"],
        "HCG DSNU": hcg["dsnu_e"],
        "HCG PRNU": hcg["prnu_percent"],
        "HCG saturation capacity": hcg["saturation_capacity_e"],
        "HCG linearity residual": hcg["linearity_residual"],
        "HCG dynamic range": hcg["dynamic_range_db"],
        "HCG system gain relative error": abs(hcg["provenance"]["system_gain_relative_error"])
        * 100.0,
    }
    for name, value in expected.items():
        assert name in summary_rows, name
        # Report cells are rounded to 3-4 significant decimals; the 0.5 %
        # comparison still catches a stale number while allowing that rounding.
        assert abs(_first_number(summary_rows[name][1])) == pytest.approx(value, rel=5e-3)
        assert summary_rows[name][3] == "PASS"

    dark = payload["dark_current"]
    assert dark["frames_per_level"] == 16
    assert dark["base_seed"] == 21
    assert dark["model"] == "D(T) - D(25 C) over the same temperature list"
    for temperature, measured, model in zip(
        dark["measured_temperatures_c"],
        dark["measured_rates_e_per_s"],
        dark["model_rates_e_per_s"],
        strict=True,
    ):
        if temperature < 65.0:
            continue
        name = f"Dark current at {temperature:g} C (differential)"
        assert name in summary_rows, name
        assert _first_number(summary_rows[name][1]) == pytest.approx(measured, rel=1e-3)
        assert _first_number(summary_rows[name][2]) == pytest.approx(model, rel=1e-3)
        assert summary_rows[name][3] == "PASS"

    dark_table = next(table for table in tables if str(table["header"][0]) == "Temperature")
    dark_rows = {
        str(row[0]): row for row in dark_table["rows"] if isinstance(row, list) and len(row) == 4
    }
    for temperature, measured, model in zip(
        dark["measured_temperatures_c"],
        dark["measured_rates_e_per_s"],
        dark["model_rates_e_per_s"],
        strict=True,
    ):
        row = dark_rows[f"{temperature:g} C"]
        assert _first_number(row[1]) == pytest.approx(measured, rel=1e-3)
        assert _first_number(row[2]) == pytest.approx(model, rel=1e-3)
        difference = (measured - model) / model * 100.0
        assert _first_number(row[3]) == pytest.approx(difference, abs=0.06)
